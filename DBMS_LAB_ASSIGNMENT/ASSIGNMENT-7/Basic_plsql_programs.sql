DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
  FROM EMPLOYEE
  WHERE JOB = 'Manager';
  DBMS_OUTPUT.PUT_LINE('No. of Managers: ' || v_count);
END;

