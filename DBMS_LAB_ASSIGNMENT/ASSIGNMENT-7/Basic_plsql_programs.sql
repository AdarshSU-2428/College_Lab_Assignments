BEGIN
  SELECT ENAME INTO v_name
  FROM EMPLOYEE
  WHERE COMM = (SELECT MAX(COMM) FROM EMPLOYEE);
  DBMS_OUTPUT.PUT_LINE('Highest Commission: ' || v_name);
END;

