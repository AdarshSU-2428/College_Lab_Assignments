DECLARE
  v_high EMPLOYEE.ENAME%TYPE;
  v_low EMPLOYEE.ENAME%TYPE;
BEGIN
  SELECT ENAME INTO v_high FROM EMPLOYEE
  WHERE SALARY = (SELECT MAX(SALARY) FROM EMPLOYEE);
  SELECT ENAME INTO v_low FROM EMPLOYEE
  WHERE SALARY = (SELECT MIN(SALARY) FROM EMPLOYEE);
  DBMS_OUTPUT.PUT_LINE('Highest: ' || v_high);
  DBMS_OUTPUT.PUT_LINE('Lowest: ' || v_low);
END;

