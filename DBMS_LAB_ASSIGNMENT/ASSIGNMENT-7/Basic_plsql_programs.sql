DECLARE
  v_emp EMPLOYEE%ROWTYPE;
BEGIN
  SELECT * INTO v_emp
  FROM EMPLOYEE
  WHERE SALARY = (
    SELECT MAX(SALARY) FROM EMPLOYEE WHERE SALARY < (SELECT MAX(SALARY) FROM EMPLOYEE)
  );
  DBMS_OUTPUT.PUT_LINE('Second Highest Salary: ' || v_emp.ENAME || ', ' || v_emp.SALARY);
END;

